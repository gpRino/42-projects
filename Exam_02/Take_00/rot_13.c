#include <unistd.h>

int main(int argc, char **argv)
{
    int i = 0;
    char c;

    if (argc != 2)
        write(1, "\n", 1);
    return (0);
    while (argv[1][i] != '\0')
    {
        while ((argv[1][i] >= 65 && argv[1][i] <= 90) || (argv[1][i] >= 97 && argv[1][i] <= 122))
        {
            if ((argv[1][i] >= 65 && argv[1][i] <= 77) || (argv[1][i] >= 97 && argv[1][i] <= 109))
            {
                c = argv[1][i] + 13;
                write(1, &c, 1);
            }
            else
            {
                c = argv[1][i] - 13;
                write(1, &c, 1);
            }
            i++;
        }
        while (argv[1][i] != '\0' && !((argv[1][i] >= 65 && argv[1][i] <= 90) || (argv[1][i] >= 97 && argv[1][i] <= 122)))
        {
            write(1, &argv[1][i], 1);
            i++;
        }
    }
    write(1, "\n", 1);
    return (0);
}