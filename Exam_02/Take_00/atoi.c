int ft_atoi(const char *str)
{
    int i;
    int sign;

    while (*str == ' ' || *str == '\t' || *str == '\n' || *str == '\v' || *str == '\f' || *str == '\r')
        str++;
    if (!str)
        return (0);
    sign = 1;
    if (*str == '-' || *str == '+')
    {
        if (*str == '-')
            sign *= -1;
        str++;
    }
    i = 0;
    while (*str >= '0' && *str <= '9')
    {
        i = i * 10 + (*str - '0');
        str++;
    }
    return (i * sign);
}   